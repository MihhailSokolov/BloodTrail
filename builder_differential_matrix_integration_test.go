// --- Criteria construction and anchor discovery. ---

// relCriteria builds the single graph.Criteria a RelSpec-shaped query needs
// -- always exactly one Filter call (recognize.FromRelCriteria's accepted
// shape) -- combining an edge-kind KindIn with any of a start/end id
// equality and a start/end endpoint-kind constraint the caller supplies.
// Exactly one part (the bare KindIn) is returned unwrapped when nothing else
// is requested, matching the bare-KindMatcher shape BloodHound's own
// builder queries construct; two or more parts are combined with query.And.
func relCriteria(edgeKind graph.Kind, startID, endID *graph.ID, startKind, endKind graph.Kind) graph.Criteria {
	parts := []graph.Criteria{query.KindIn(query.Relationship(), edgeKind)}

	if startID != nil {
		parts = append(parts, query.Equals(query.StartID(), *startID))
	}
	if endID != nil {
		parts = append(parts, query.Equals(query.EndID(), *endID))
	}
	if startKind != nil {
		parts = append(parts, query.Kind(query.Start(), startKind))
	}
	if endKind != nil {
		parts = append(parts, query.Kind(query.End(), endKind))
	}

	if len(parts) == 1 {
		return parts[0]
	}
	return query.And(parts...)
}

// kindPairCap bounds how many node-kind pairs selectKindPairs returns:
// the fixtures graph alone carries 13 node kinds (78 unordered pairs), and
// testing every one of them, at three ops apiece, across 21 graphs would
// push this suite well past a sane runtime for no material extra coverage
// -- any-of kind matching is the same bitset-union operation regardless of
// which two kinds are named.
const kindPairCap = 20

// selectKindPairs returns every unordered pair of distinct kinds in kinds,
// downsampled to at most maxPairs by taking an evenly spaced subset
// (deterministic, so a failure reproduces identically on rerun) whenever the
// full combinatorial count would exceed it.
func selectKindPairs(kinds graph.Kinds, maxPairs int) [][2]graph.Kind {
	var all [][2]graph.Kind
	for i := 0; i < len(kinds); i++ {
		for j := i + 1; j < len(kinds); j++ {
			all = append(all, [2]graph.Kind{kinds[i], kinds[j]})
		}
	}

	if maxPairs <= 0 || len(all) <= maxPairs {
		return all
	}

	selected := make([][2]graph.Kind, 0, maxPairs)
	step := float64(len(all)) / float64(maxPairs)
	for i := 0; i < maxPairs; i++ {
		selected = append(selected, all[int(float64(i)*step)])
	}
	return selected
}

// firstEdgeAnchor derives a real (start, end) id pair for kind directly from
// oracle's own data -- the first (by relationship id) relationship of that
// kind -- rather than any hardcoded id. ok is false when the graph currently
// has no relationship of this kind, in which case the caller skips the
// existing-anchor variants for it (the nonexistent-id variant, run
// unconditionally, still exercises the anchored code paths for such a
// kind).
func firstEdgeAnchor(t *testing.T, ctx context.Context, oracle graph.Database, kind graph.Kind) (start, end graph.ID, ok bool) {
	t.Helper()

	triples := relTriplesByCriteria(t, ctx, oracle, query.KindIn(query.Relationship(), kind))
	if len(triples) == 0 {
		return 0, 0, false
	}
	return triples[0].StartID, triples[0].EndID, true
}

// firstNodeKindOf derives the first graph.Kind id itself carries, again
// read directly off oracle's data. Used to build a non-trivial (likely to
// actually match something) endpoint-kind constraint for the
// endpoint-kind-constrained variants below, rather than picking an arbitrary
// kind from the graph's alphabet that may have nothing to do with the
// anchor node in question.
func firstNodeKindOf(t *testing.T, ctx context.Context, oracle graph.Database, id graph.ID) (graph.Kind, bool) {
	t.Helper()

	var kinds graph.Kinds
	if err := oracle.ReadTransaction(ctx, func(tx graph.Transaction) error {
		node, err := tx.Nodes().Filter(query.Equals(query.NodeID(), id)).First()
		if err != nil {
			return err
		}
		kinds = node.Kinds
		return nil
	}); err != nil {
		t.Fatalf("fetch node %d: %v", id, err)
	}

	if len(kinds) == 0 {
		return nil, false
	}
	return kinds[0], true
}

// --- The matrix itself. ---

// runBuilderQueryDifferentialMatrix runs this file's whole differential
// matrix (see the top-of-file doc) against one already-loaded, already
// rebuilt graph, comparing bt (the wrapped driver under test) against
// oracle (the raw pg driver oracle) for every node kind, a bounded set of
// node-kind pairs, and every edge kind crossed with anchor variant,
// endpoint-kind constraint, and the two .Query() projections.
//
// It fails the calling graph outright (t.Fatalf) if graphServed -- the
// summed builder-served marker delta across every check this function
// runs -- never advances past zero: a graph whose every single query
// delegated to PostgreSQL proves nothing about the serving stack this suite
// exists to validate (see this file's top doc, "Anti-vacuity").
func runBuilderQueryDifferentialMatrix(t *testing.T, ctx context.Context, bt, oracle graph.Database, buf *lockedBuffer, tally map[string]int, nodeKinds, edgeKinds graph.Kinds) {
	t.Helper()

	assertSentinelIDAbsent(t, ctx, oracle)

	graphServed := 0

	// --- Every node kind: NodeSpec-shaped Count/FetchIDs/FetchKinds. ---
	for _, kind := range nodeKinds {
		crit := query.Kind(query.Node(), kind)
		label := fmt.Sprintf("node kind=%s", kind)

		checkNodeCount(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
		checkNodeFetchIDs(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
		checkNodeFetchKinds(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
	}

	// --- A bounded set of node-kind pairs: the same three ops, any-of. ---
	for _, pair := range selectKindPairs(nodeKinds, kindPairCap) {
		crit := query.KindIn(query.Node(), pair[0], pair[1])
		label := fmt.Sprintf("node kinds=%s|%s (any-of)", pair[0], pair[1])

		checkNodeCount(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
		checkNodeFetchIDs(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
		checkNodeFetchKinds(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
	}

	// --- Every edge kind x anchor variant, endpoint-kind constraints, and
	// the two .Query() projections. ---
	missingID := nonexistentID
	for _, kind := range edgeKinds {
		anchorStart, anchorEnd, hasEdge := firstEdgeAnchor(t, ctx, oracle, kind)

		var (
			startKind, endKind         graph.Kind
			haveStartKind, haveEndKind bool
		)
		if hasEdge {
			startKind, haveStartKind = firstNodeKindOf(t, ctx, oracle, anchorStart)
			endKind, haveEndKind = firstNodeKindOf(t, ctx, oracle, anchorEnd)
		}
		// Fall back to an arbitrary (but still real, present-in-this-graph)
		// node kind when this edge kind currently has no edge to derive one
		// from -- still a well-formed, if less likely to match, constraint.
		if !haveStartKind {
			startKind = nodeKinds[0]
		}
		if !haveEndKind {
			endKind = nodeKinds[len(nodeKinds)-1]
		}

		// anchor = none, plus the unanchored pair-rows projection.
		kindOnly := relCriteria(kind, nil, nil, nil, nil)
		label := fmt.Sprintf("edge kind=%s anchor=none", kind)
		checkRelCount(t, ctx, bt, oracle, buf, tally, &graphServed, label, kindOnly)
		checkRelFetchIDs(t, ctx, bt, oracle, buf, tally, &graphServed, label, kindOnly)
		checkRelFetchTriples(t, ctx, bt, oracle, buf, tally, &graphServed, label, kindOnly)
		checkRelFetchKinds(t, ctx, bt, oracle, buf, tally, &graphServed, label, kindOnly)
		checkPairRows(t, ctx, bt, oracle, buf, tally, &graphServed, label+" pairRows", kindOnly)

		// anchor = start, existing id (only when this kind has an edge) plus
		// the outbound step-rows projection.
		if hasEdge {
			crit := relCriteria(kind, &anchorStart, nil, nil, nil)
			label = fmt.Sprintf("edge kind=%s anchor=start(existing)", kind)
			checkRelCount(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchIDs(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchTriples(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchKinds(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkStepRows(t, ctx, bt, oracle, buf, tally, &graphServed, label+" stepRows", crit, true)
		}

		// anchor = start, nonexistent id -- unconditional, expect empty.
		{
			crit := relCriteria(kind, &missingID, nil, nil, nil)
			label = fmt.Sprintf("edge kind=%s anchor=start(nonexistent)", kind)
			checkRelCount(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchIDs(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchTriples(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchKinds(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkStepRows(t, ctx, bt, oracle, buf, tally, &graphServed, label+" stepRows", crit, true)
		}

		// anchor = end, existing id, plus the inbound step-rows mirror.
		if hasEdge {
			crit := relCriteria(kind, nil, &anchorEnd, nil, nil)
			label = fmt.Sprintf("edge kind=%s anchor=end(existing)", kind)
			checkRelCount(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchIDs(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchTriples(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchKinds(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkStepRows(t, ctx, bt, oracle, buf, tally, &graphServed, label+" stepRows", crit, false)
		}

		// anchor = end, nonexistent id -- unconditional, expect empty.
		{
			crit := relCriteria(kind, nil, &missingID, nil, nil)
			label = fmt.Sprintf("edge kind=%s anchor=end(nonexistent)", kind)
			checkRelCount(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchIDs(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchTriples(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchKinds(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkStepRows(t, ctx, bt, oracle, buf, tally, &graphServed, label+" stepRows", crit, false)
		}

		// anchor = both (existing ids only).
		if hasEdge {
			crit := relCriteria(kind, &anchorStart, &anchorEnd, nil, nil)
			label = fmt.Sprintf("edge kind=%s anchor=both", kind)
			checkRelCount(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchIDs(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchTriples(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchKinds(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
		}

		// Endpoint-kind-constrained variants: unanchored, but with the
		// start (resp. end) side further constrained to a real kind
		// derived from the graph's own data.
		{
			crit := relCriteria(kind, nil, nil, startKind, nil)
			label = fmt.Sprintf("edge kind=%s start-kind=%s", kind, startKind)
			checkRelCount(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchIDs(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchTriples(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchKinds(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
		}
		{
			crit := relCriteria(kind, nil, nil, nil, endKind)
			label = fmt.Sprintf("edge kind=%s end-kind=%s", kind, endKind)
			checkRelCount(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchIDs(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchTriples(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
			checkRelFetchKinds(t, ctx, bt, oracle, buf, tally, &graphServed, label, crit)
		}
	}

	if graphServed == 0 {
		t.Fatalf("builder-served marker never advanced across this graph's %d-node-kind/%d-edge-kind matrix -- every single query delegated to PostgreSQL, which proves nothing about the serving stack", len(nodeKinds), len(edgeKinds))
	}
}

// TestBuilderQueryDifferentialMatrix is Task 12's deliverable: opens a real
// *Driver (bt) alongside a raw pg driver oracle on the same PostgreSQL
// database, then runs runBuilderQueryDifferentialMatrix once for the hand
// fixtures and once per random-graph seed (1..builderMatrixRandomSeeds),
// wiping and reloading the graph and forcing a deterministic RebuildNow
// (via the unexported Driver.engine field -- see this file's top doc for
// why that access is available and needed here) before each run so every
// comparison sees a known-fresh snapshot.
//
// After every graph has run, it additionally asserts that all nine op
// families (allOpFamilies) were served by the engine at least once
// somewhere in the whole suite -- the whole-suite half of this file's
// anti-vacuity contract; each individual graph's own per-graph skip-guard
// is runBuilderQueryDifferentialMatrix's job (see its own doc).
func TestBuilderQueryDifferentialMatrix(t *testing.T) {
	dsn := graphtest.PGAvailable(t)

	// Every snapshot observed below is the direct, deterministic result of
	// this test's own RebuildNow calls, each made right after loading that
	// graph's own data -- waitForBootLoad (right after AssertSchema, below)
	// is what makes that true, not mere luck of timing: WipeGraph/LoadDataset
	// both write through pgDriver, the raw driver, never through bt's Apply
	// path, so nothing here bumps applyEpoch, and a still-in-flight boot-load
	// LoadSnapshot call would have no epoch check stopping it from adopting
	// AFTER this test's own explicit RebuildNow and silently overwriting the
	// freshly loaded fixture/seed graph with whatever (possibly stale,
	// possibly mid-wipe) state existed when it started reading. Waiting for
	// boot load to settle before any of that runs removes the race outright,
	// rather than merely arguing it away.
	buf := installLogCapture(t)

	ctx := context.Background()

	pgDriver, pool := graphtest.OpenPG(t, dsn)
	cfg := dawgs.Config{ConnectionString: dsn, GraphQueryMemoryLimit: size.Gibibyte, Pool: pool}

	bt, err := dawgs.Open(ctx, DriverName, cfg)
	if err != nil {
		t.Fatalf("open bloodtrail: %v", err)
	}
	defer func() { _ = bt.Close(ctx) }()

	d, ok := bt.(*Driver)
	if !ok {
		t.Fatalf("expected *Driver, got %T", bt)
	}
	// AssertSchema's default-graph target is tracked per driver instance
	// (not auto-discovered from the database by a freshly opened one), so
	// this wrapped driver needs its own call even though graphtest.OpenPG
	// already asserted the same graph, by name, for pgDriver above.
	if err := bt.AssertSchema(ctx, graph.Schema{DefaultGraph: graph.Graph{Name: graphtest.GraphName}}); err != nil {
		t.Fatalf("assert schema (bt): %v", err)
	}

	waitForBootLoad(t, d)

	oracle, err := dawgs.Open(ctx, pg.DriverName, cfg)
	if err != nil {
		t.Fatalf("open pg oracle: %v", err)
	}
	defer func() { _ = oracle.Close(ctx) }()
	if err := oracle.AssertSchema(ctx, graph.Schema{DefaultGraph: graph.Graph{Name: graphtest.GraphName}}); err != nil {
		t.Fatalf("assert schema (oracle): %v", err)
	}

	tally := make(map[string]int, len(allOpFamilies))

	// --- Graph 1: the hand fixtures. ---
	t.Run("fixtures", func(t *testing.T) {
		graphtest.WipeGraph(t, pgDriver)
		for _, path := range builderMatrixFixturePaths {
			graphtest.LoadDataset(t, pgDriver, path)
		}
		if err := d.engine.RebuildNow(ctx, "matrix_test"); err != nil {
			t.Fatalf("RebuildNow: %v", err)
		}

		nodeKinds, edgeKinds := builderMatrixFixtureKinds(t)
		runBuilderQueryDifferentialMatrix(t, ctx, bt, oracle, buf, tally, nodeKinds, edgeKinds)
	})

	// --- Write-through rerun: the SAME fixtures graph (no rewipe), mutated
	// through bt's own write path, then the identical matrix rerun with
	// RebuildCount pinned -- see runBuilderMatrixWriteThroughPreamble's own
	// doc for the full design. writeThroughPreambleEnabled (prebuilt_corpus_
	// integration_test.go, this same package) gates this phase, shared with
	// that file's own "writethrough" subtest; on by default since it is
	// cheap.
	if writeThroughPreambleEnabled() {
		t.Run("fixtures_writethrough", func(t *testing.T) {
			nodeKinds, edgeKinds := builderMatrixFixtureKinds(t)

			rebuilds := d.engine.RebuildCount()
			fallbacks := markerCount(buf, fallbackEnteredMarker)

			runBuilderMatrixWriteThroughPreamble(t, ctx, bt, oracle, pool, nodeKinds, edgeKinds)

			runBuilderQueryDifferentialMatrix(t, ctx, bt, oracle, buf, tally, nodeKinds, edgeKinds)

			assertRebuildCountUnchanged(t, d, rebuilds, t.Name())
			assertNoNewFallback(t, buf, fallbacks, t.Name())
		})
	}

	// --- Graphs 2..21: 20 seeded random graphs. ---
	for seed := int64(1); seed <= builderMatrixRandomSeeds; seed++ {
		t.Run(fmt.Sprintf("random/seed=%d", seed), func(t *testing.T) {
			graphtest.WipeGraph(t, pgDriver)
			loadBuilderMatrixRandomGraph(t, pgDriver, seed)
			if err := d.engine.RebuildNow(ctx, "matrix_test"); err != nil {
				t.Fatalf("RebuildNow (seed=%d): %v", seed, err)
			}

			runBuilderQueryDifferentialMatrix(t, ctx, bt, oracle, buf, tally, graphtest.RandomNodeKinds, graphtest.RandomEdgeKinds)
		})
	}

	for _, family := range allOpFamilies {
		if tally[family] == 0 {
			t.Errorf("op family %q was never served by the engine anywhere in this suite -- a recognizer regression affecting exactly this family would go unnoticed", family)
		}
	}
}

// runBuilderMatrixWriteThroughPreamble performs a small, standard mutation
// batch through bt against the "fixtures" graph already loaded by
// TestBuilderQueryDifferentialMatrix's own "fixtures" subtest, leaving the
// replica in write-through-derived (not rebuild-derived) state before the
// caller reruns runBuilderQueryDifferentialMatrix over the same graph --
// re-basing this suite's structural matrix on write-through, mirroring
// prebuilt_corpus_integration_test.go's own runCorpusWriteThroughPreamble
// for its 222-query corpus (see that function's doc for the shared design
// rationale: reuse already-proven write-observer-recognized shapes so this
// preamble carries no risk of tripping fallback by accident).
//
// Uses write-through's classes 1 (objectid upsert create), 2 (objectid upsert
// merge), 5 (batch.UpdateNodes kinds+deleted prop), and 7 (batch.
// DeleteRelationship by id) -- the same four prebuilt_corpus_integration_
// test.go's own preamble uses -- against nodeKinds[0]/edgeKinds[0] (real
// kinds this specific graph carries, derived by the caller's own
// builderMatrixFixtureKinds, never hardcoded) so the mutations are counted
// by, not invisible to, the structural matrix's own per-kind Count/FetchIDs/
// FetchKinds/FetchTriples/pair-row/step-row checks that follow.
func runBuilderMatrixWriteThroughPreamble(t *testing.T, ctx context.Context, bt, oracle graph.Database, pool *pgxpool.Pool, nodeKinds, edgeKinds graph.Kinds) {
	t.Helper()

	// Read BEFORE any write below -- see prebuilt_corpus_integration_test.go's
	// runCorpusWriteThroughPreamble's identical reasoning: class 2 must
	// merge onto a genuinely pre-existing node, not (by scan-order
	// accident) the brand-new one class 1 is about to create. This
	// fixtures graph carries exactly one objectid-bearing node today
	// (adcs_fanout.json's lone Group node); if a future fixture edit adds
	// none at all, this read comes back "" and class 2 below degrades to
	// upserting a fresh (rather than merged) node under that empty-string
	// objectid, which still exercises the same write shape, just without an
	// existing target to merge onto.
	existingOID := cypherStringValue(t, ctx, oracle, `MATCH (n) WHERE n.objectid IS NOT NULL RETURN n.objectid LIMIT 1`)

	// Asserted through a THROWAWAY *pg.Driver sharing bt's own connection
	// pool, never through bt (or pgDriver/oracle) itself -- see
	// prebuilt_corpus_integration_test.go's runCorpusWriteThroughPreamble
	// doc, "Why the constraint is asserted through a THROWAWAY driver, not
	// bt itself", for the full derivation. Every driver instance already in
	// scope by this point (bt, pgDriver, oracle) already asserted
	// graphtest.GraphName's schema at least once before this preamble runs,
	// so each one's own SchemaManager cache would fast-path a same-name
	// re-assert into a no-op that never issues the real CREATE UNIQUE INDEX
	// -- confirmed the same way for this file (PostgreSQL error 42P10 on
	// the very next UpdateNodeBy) before this fix.
	schema := graph.Schema{DefaultGraph: graph.Graph{
		Name:            graphtest.GraphName,
		NodeConstraints: []graph.Constraint{{Field: "objectid", Type: graph.BTreeIndex}},
	}}
	if err := pg.NewDriver(size.Gibibyte, pool).AssertSchema(ctx, schema); err != nil {
		t.Fatalf("write-through preamble: assert schema with objectid constraint: %v", err)
	}

	primaryKind := nodeKinds[0]
	tempKind := graph.StringKind("WT18MatrixTemp")
	taggedKind := graph.StringKind("WT18MatrixTagged")
	mergedKind := graph.StringKind("WT18MatrixMerged")

	// Class 1: objectid upsert creating a brand-new node of a REAL fixture
	// kind, counted by that kind's Count/FetchIDs/FetchKinds checks in the
	// rerun that follows.
	const newObjectID = "WT18-MatrixPreambleNode"
	if err := bt.BatchOperation(ctx, func(batch graph.Batch) error {
		return batch.UpdateNodeBy(objectIDUpdate(newObjectID, graph.NewProperties().Set("wt18temp", "gone-soon"), primaryKind, tempKind))
	}); err != nil {
		t.Fatalf("write-through preamble: objectid upsert create: %v", err)
	}

	newNodeResult, err := runCorpusQuery(t, ctx, bt, fmt.Sprintf(`MATCH (n) WHERE n.objectid = %s RETURN n`, cypherStringLiteral(newObjectID)))
	if err != nil {
		t.Fatalf("write-through preamble: locate new node: %v", err)
	}
	newIDs := extractNodeIDs(newNodeResult)
	if len(newIDs) != 1 {
		t.Fatalf("write-through preamble: locate new node: got %d nodes, want 1", len(newIDs))
	}
	newNodeID := newIDs[0]

	// Class 2: objectid upsert merging a kind onto whichever node
	// existingOID (read above, before any write) names.
	if err := bt.BatchOperation(ctx, func(batch graph.Batch) error {
		return batch.UpdateNodeBy(objectIDUpdate(existingOID, graph.NewProperties().Set("wt18merged", "yes"), mergedKind))
	}); err != nil {
		t.Fatalf("write-through preamble: objectid upsert merge: %v", err)
	}

	// Class 5: batch.UpdateNodes carrying AddedKinds/DeletedKinds and a
	// deleted property, targeting the class-1 node above by id.
	update := &graph.Node{ID: newNodeID, Kinds: graph.Kinds{taggedKind}, DeletedKinds: graph.Kinds{tempKind}, Properties: graph.NewProperties()}
	update.Properties.Delete("wt18temp")
	if err := bt.BatchOperation(ctx, func(batch graph.Batch) error {
		return batch.UpdateNodes([]*graph.Node{update})
	}); err != nil {
		t.Fatalf("write-through preamble: batch UpdateNodes: %v", err)
	}

	// Class 7: batch.DeleteRelationship by id -- a real edge of the
	// fixture's first edge kind, discovered via this file's own
	// relTriplesByCriteria (never hardcoded).
	triples := relTriplesByCriteria(t, ctx, oracle, query.KindIn(query.Relationship(), edgeKinds[0]))
	if len(triples) == 0 {
		t.Fatalf("write-through preamble: no existing %s relationship to delete", edgeKinds[0])
	}
	if err := bt.BatchOperation(ctx, func(batch graph.Batch) error {
		return batch.DeleteRelationship(triples[0].ID)
	}); err != nil {
		t.Fatalf("write-through preamble: DeleteRelationship: %v", err)
	}
}
