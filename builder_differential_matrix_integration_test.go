// builderMatrixFixturePaths are the same two opengraph datasets
// driver_integration_test.go's datasets loads, merged into one graph here
// the same way loadDatasets does (via graphtest.LoadDataset, called once
// per path against the same driver).
var builderMatrixFixturePaths = []string{
	"testdata/dawgs/traversal_shapes.json",
	"testdata/dawgs/adcs_fanout.json",
}

// builderMatrixFixtureKinds parses both fixture files (without loading them
// -- graphtest.LoadDataset does that separately) purely to recover their
// node/edge kind alphabets, the same way driver_integration_test.go's
// schemaFromDatasets does; duplicated here rather than called directly since
// schemaFromDatasets lives in package bloodtrail_test, a different package
// from this file's package bloodtrail.
func builderMatrixFixtureKinds(t *testing.T) (nodeKinds, edgeKinds graph.Kinds) {
	t.Helper()

	for _, path := range builderMatrixFixturePaths {
		f, err := os.Open(path)
		if err != nil {
			t.Fatalf("open %s: %v", path, err)
		}
		doc, err := opengraph.ParseDocument(f)
		_ = f.Close()
		if err != nil {
			t.Fatalf("parse %s: %v", path, err)
		}

		nk, ek := doc.Graph.Kinds()
		nodeKinds = nodeKinds.Add(nk...)
		edgeKinds = edgeKinds.Add(ek...)
	}

	return nodeKinds, edgeKinds
}

// --- Graph source 2: 20 seeded random graphs. ---

const (
	// builderMatrixRandomSeeds is the seed range TestBuilderQueryDifferentialMatrix
	// sweeps for its random-graph source; fixed for reproducibility, exactly
	// like internal/engine/random_differential_integration_test.go's own
	// randomDifferentialSeeds.
	builderMatrixRandomSeeds = 20

	// builderMatrixRandomNodes and builderMatrixRandomEdges size each random
	// graph. Deliberately smaller than graphtest.LoadRandom's fixed 60
	// nodes/180 edges: this suite's per-graph query count is already the
	// product of every node/edge kind, several anchor variants, and up to
	// four ops each, so keeping each individual graph small is what keeps
	// the full 20-seed sweep (see this file's top doc) under a couple of
	// minutes. The kind alphabet itself is unchanged (graphtest.
	// RandomNodeKinds/RandomEdgeKinds, 5/6 kinds) so the matrix's shape is
	// identical to what a full-size LoadRandom graph would produce, just
	// with less data to scan per query.
	builderMatrixRandomNodes = 40
	builderMatrixRandomEdges = 120
)

// loadBuilderMatrixRandomGraph generates a pseudo-random graph from seed
// into pgDriver's default graph, replicating graphtest.LoadRandom's exact
// generation algorithm (independent uniform draws for each node's kind and
// each edge's endpoints/kind, nodes via a write transaction so their ids are
// known, edges via BatchOperation) at builderMatrixRandomNodes/
// builderMatrixRandomEdges scale instead of LoadRandom's fixed 60/180 -- see
// those consts' doc for why this suite needs its own, smaller sizing rather
// than calling the shared, exported graphtest.LoadRandom directly.
// graphtest.LoadRandom itself is left completely untouched: it is shared
// infrastructure internal/engine's own random differential suite already
// depends on at its documented size, and changing that size would be an
// unrelated, unnecessary risk to take on for this task.
//
// Reuses graphtest.RandomNodeKinds/RandomEdgeKinds/GraphName so a caller
// comparing this suite's random graphs against internal/engine's own knows
// they are drawn from the identical kind alphabet, just a different
// (smaller) node/edge count.
func loadBuilderMatrixRandomGraph(t *testing.T, pgDriver *pg.Driver, seed int64) {
	t.Helper()
	ctx := context.Background()

	rng := rand.New(rand.NewSource(seed))

	schema := graph.Schema{Graphs: []graph.Graph{{Name: graphtest.GraphName, Nodes: graphtest.RandomNodeKinds, Edges: graphtest.RandomEdgeKinds}}}
	if err := pgDriver.AssertSchema(ctx, schema); err != nil {
		t.Fatalf("builder matrix: random graph (seed=%d): assert schema: %v", seed, err)
	}

	ids := make([]graph.ID, builderMatrixRandomNodes)
	if err := pgDriver.WriteTransaction(ctx, func(tx graph.Transaction) error {
		for i := range ids {
			kind := graphtest.RandomNodeKinds[rng.Intn(len(graphtest.RandomNodeKinds))]

			node, err := tx.CreateNode(graph.NewProperties(), kind)
			if err != nil {
				return err
			}
			ids[i] = node.ID
		}
		return nil
	}); err != nil {
		t.Fatalf("builder matrix: random graph (seed=%d): create nodes: %v", seed, err)
	}

	if err := pgDriver.BatchOperation(ctx, func(batch graph.Batch) error {
		for i := 0; i < builderMatrixRandomEdges; i++ {
			start := ids[rng.Intn(len(ids))]
			end := ids[rng.Intn(len(ids))]
			kind := graphtest.RandomEdgeKinds[rng.Intn(len(graphtest.RandomEdgeKinds))]

			// CreateRelationship, not the deprecated CreateRelationshipByIDs
			// graphtest.LoadRandom itself still uses (shared infra this
			// function otherwise mirrors, left untouched -- see this
			// function's own doc): the two are exactly equivalent (pg's own
			// batch.CreateRelationshipByIDs is a thin wrapper that builds
			// the same *graph.Relationship, ID left zero, and calls this),
			// so this file's own code can use the non-deprecated spelling
			// with no behavior change.
			if err := batch.CreateRelationship(graph.NewRelationship(0, start, end, graph.NewProperties(), kind)); err != nil {
				return err
			}
		}
		return nil
	}); err != nil {
		t.Fatalf("builder matrix: random graph (seed=%d): create edges: %v", seed, err)
	}
}

// --- The nonexistent-id sentinel every anchor variant is also run against. ---

// nonexistentID is the id every anchor variant below also exercises,
// expecting an empty (but still oracle-matching) result: PostgreSQL's own
// id columns are BIGSERIAL, assigning ids starting at 1, so 0 is never a
// database id any dataset or generator in this suite could produce.
// assertSentinelIDAbsent verifies this assumption directly, once per graph,
// rather than trusting it silently.
const nonexistentID = graph.ID(0)

// assertSentinelIDAbsent fails the test outright if nonexistentID somehow
// exists as a node or relationship id in oracle's current data -- a defensive
// check for the "expect empty results" contract every anchor variant's
// nonexistent-id case below relies on.
func assertSentinelIDAbsent(t *testing.T, ctx context.Context, oracle graph.Database) {
	t.Helper()

	if n := nodeCountByCriteria(t, ctx, oracle, query.Equals(query.NodeID(), nonexistentID)); n != 0 {
		t.Fatalf("sentinel id %d unexpectedly exists as a node (count=%d); this suite's nonexistent-id anchor variants assume it never does", nonexistentID, n)
	}
	if n := relCountByCriteria(t, ctx, oracle, query.Equals(query.RelationshipID(), nonexistentID)); n != 0 {
		t.Fatalf("sentinel id %d unexpectedly exists as a relationship (count=%d); this suite's nonexistent-id anchor variants assume it never does", nonexistentID, n)
	}
}

// --- Criteria-based query helpers, run identically against bt and oracle. ---
//
// These mirror engine_serving_integration_test.go's kind-keyed
// nodeCountByKind/relCountByKind/etc., generalized to take an arbitrary
// graph.Criteria (a bare kind filter, a KindIn any-of, or a full
// And(kind, id, endpoint-kind) conjunction) instead of a single kind, since
// this suite's matrix needs far more criteria shapes than "by one kind."

func nodeCountByCriteria(t *testing.T, ctx context.Context, db graph.Database, criteria graph.Criteria) int64 {
	t.Helper()

	var count int64
	if err := db.ReadTransaction(ctx, func(tx graph.Transaction) error {
		n, err := tx.Nodes().Filter(criteria).Count()
		count = n
		return err
	}); err != nil {
		t.Fatalf("Nodes().Filter(...).Count(): %v", err)
	}
	return count
}

func nodeIDsByCriteria(t *testing.T, ctx context.Context, db graph.Database, criteria graph.Criteria) []graph.ID {
	t.Helper()

	var ids []graph.ID
	if err := db.ReadTransaction(ctx, func(tx graph.Transaction) error {
		return tx.Nodes().Filter(criteria).FetchIDs(func(cursor graph.Cursor[graph.ID]) error {
			for id := range cursor.Chan() {
				ids = append(ids, id)
			}
			return cursor.Error()
		})
	}); err != nil {
		t.Fatalf("Nodes().Filter(...).FetchIDs(): %v", err)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	return ids
}

// canonicalKindsRow is graph.KindsResult (nodes) reduced to a comparable
// value: graph.KindsResult itself holds a graph.Kinds slice, which cannot be
// compared with == (and so cannot satisfy a `comparable` type parameter),
// but a node's own kind *list* is unordered from either driver's
// perspective, so its names are sorted and joined into one string here --
// canonicalizeKindNames -- before the row is otherwise treated as plain,
// comparable data.
type canonicalKindsRow struct {
	id    graph.ID
	kinds string
}

// canonicalizeKindNames renders kinds as a sorted, comma-joined string, so
// two kind lists that carry the same kinds in different orders (e.g. one
// side derived from a bitset's iteration order, the other from a SQL
// array) compare equal.
func canonicalizeKindNames(kinds graph.Kinds) string {
	names := append([]string(nil), kinds.Strings()...)
	sort.Strings(names)
	return strings.Join(names, ",")
}

func nodeKindsByCriteria(t *testing.T, ctx context.Context, db graph.Database, criteria graph.Criteria) []canonicalKindsRow {
	t.Helper()

	var rows []canonicalKindsRow
	if err := db.ReadTransaction(ctx, func(tx graph.Transaction) error {
		return tx.Nodes().Filter(criteria).FetchKinds(func(cursor graph.Cursor[graph.KindsResult]) error {
			for row := range cursor.Chan() {
				rows = append(rows, canonicalKindsRow{id: row.ID, kinds: canonicalizeKindNames(row.Kinds)})
			}
			return cursor.Error()
		})
	}); err != nil {
		t.Fatalf("Nodes().Filter(...).FetchKinds(): %v", err)
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].id < rows[j].id })
	return rows
}

