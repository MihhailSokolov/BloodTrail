// This file is Task 12 of the milestone-3 plan: a differential matrix suite
// comparing every builder-query shape the wrapped driver's recording
// wrappers (node_query.go's recordingNodeQuery, relationship_query.go's
// recordingRelationshipQuery) can recognize and serve against the raw pg
// driver used as an oracle, across the project's hand fixtures and a batch
// of seeded random graphs.
//
// # File placement: root package, not internal/engine
//
// The task brief originally called for this file to live at
// internal/engine/builder_differential_integration_test.go, mirroring
// random_differential_integration_test.go's placement. It lives here
// instead, at the repository root as part of package bloodtrail, for the
// same unavoidable reason staleness_integration_test.go's own top-of-file
// doc gives for that file: this suite exercises node_query.go's
// recordingNodeQuery and relationship_query.go's recordingRelationshipQuery
// -- the wrappers that recognize a Filter'd Count/FetchIDs/FetchTriples/
// FetchKinds/Query call and decide whether to serve it from the engine --
// and those wrappers are defined in the root package. internal/engine
// cannot see them, and even if the recognition logic itself lived in
// internal/engine (some of it does, in internal/engine/recognize), driving
// an actual *bloodtrail.Driver-wrapped transaction through them would
// require internal/engine to import the root package, which already
// imports internal/engine -- an import cycle. Putting this suite in the
// root package instead resolves that: the root package already imports
// internal/engine, so a test here can freely open a real *bloodtrail.Driver
// via dawgs.Open and drive builder queries through its wrapped
// transactions.
//
// Being in package bloodtrail (not bloodtrail_test) also gives this file
// the same white-box access staleness_integration_test.go relies on: the
// unexported Driver.engine field, used below for exactly one thing --
// engine.RebuildNow, a deterministic, on-demand rebuild after each graph is
// loaded, so every comparison below runs against a known-fresh snapshot
// with no dependency on a datapipe_status table or a poller's timing.
//
// # The matrix
//
// Two graph sources, each rebuilt from scratch and run through the full
// matrix below:
//
//   - The hand fixtures already used elsewhere in this repo's integration
//     suite (testdata/dawgs/traversal_shapes.json and adcs_fanout.json),
//     loaded together via graphtest.LoadDataset exactly as
//     driver_integration_test.go's loadDatasets does.
//   - 20 seeded random graphs (seeds 1..20), generated by
//     loadBuilderMatrixRandomGraph -- a local, size-bounded adaptation of
//     internal/graphtest's own LoadRandom (see that function's doc for why
//     it is adapted rather than reused unmodified: LoadRandom's 60-node,
//     180-edge sizing was tuned for milestone 2's much lighter path-query
//     differential suite, not for this suite's dense structural matrix,
//     which multiplies every node/edge kind by several anchor variants and
//     op families).
//
// For each loaded graph, runBuilderQueryDifferentialMatrix enumerates:
//
//   - Every node kind: a NodeSpec-shaped Count/FetchIDs/FetchKinds query
//     (query.Kind(query.Node(), k)).
//   - A bounded set of node-kind pairs: the same three ops via an any-of
//     KindIn query (query.KindIn(query.Node(), k1, k2)).
//   - Every edge kind, crossed with anchor variant {none, start-anchored,
//     end-anchored, both}: Count/FetchIDs/FetchTriples/FetchKinds, plus
//     endpoint-kind-constrained variants (query.Kind(query.Start()/End(),
//     k)), plus the two canonical .Query() projections -- unanchored pair
//     rows (Returning(StartID(), EndID())) and, for start-/end-anchored
//     specs, ordered step rows (Returning(EndID(), KindsOf(End()),
//     RelationshipID(), KindsOf(Relationship())) or its inbound mirror),
//     both with OrderBy(query.Order(query.Identity(query.Relationship()),
//     query.Ascending())) exactly as dawgs' own
//     traversal.shallowFetchRelationships issues it.
//
// Anchor ids are never hardcoded: firstEdgeAnchor and firstNodeKindOf derive
// a real start/end id (and the real kind each one carries) from the
// oracle's own data for the edge kind under test, alongside a fixed
// nonexistent-id sentinel (nonexistentID) that every anchor variant is also
// exercised against, expecting an empty but still-matching result on both
// sides.
//
// Count is compared exactly; FetchIDs/FetchTriples/FetchKinds/pair rows are
// compared as sets (sorted before comparison, in equalSlices); ordered step
// rows are compared as exact sequences (never sorted -- see collectStepRows).
//
// # Anti-vacuity
//
// A suite that only ever proves "the engine and PostgreSQL agree" without
// also proving "the engine actually answered, rather than delegating every
// single query" would be evidence-free: runBuilderQueryDifferentialMatrix
// tracks graphServed, the summed builder-served marker delta across every
// check it runs, and fails the graph outright if it never advances (a
// per-graph skip-guard). TestBuilderQueryDifferentialMatrix additionally
// tallies, across the whole suite, which of the nine op families (node
// count/ids/kinds, rel count/ids/triples/kinds, pair rows, step rows) were
// ever served at least once, failing at the end if any family was not --
// catching a recognizer regression that silently starts delegating just one
// family, which a single graph's aggregate graphServed > 0 check alone could
// never distinguish from "every other family compensated."
